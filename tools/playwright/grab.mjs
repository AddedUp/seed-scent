import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto('http://127.0.0.1:3001/index.html?bust=' + Date.now())
await page.waitForFunction(() => window.__dbg && __dbg.state().ready, null, { timeout: 30000 })
await page.waitForTimeout(2500)
const h = await page.evaluate(() => __dbg.state().hero)
const px = 720 + h.x / (10 / 900), py = 450 - h.y / (10 / 900)
console.log('pendant at', px.toFixed(0), py.toFixed(0), 'world', h.x, h.y)
const under = await page.evaluate(([x, y]) => { const el = document.elementFromPoint(x, y); return el ? el.tagName + '.' + el.className : null }, [px, py])
console.log('element under pointer:', under)
await page.mouse.move(px, py)
await page.waitForTimeout(100)
console.log('cursor style after move:', await page.evaluate(() => document.body.style.cursor))
await page.mouse.down()
await page.waitForTimeout(60)
console.log('after down:', await page.evaluate(() => JSON.stringify({ held: __dbg.state().held, lastDown: __dbg.stats && __dbg.stats.lastDown })))
for (let i = 1; i <= 12; i++) { await page.mouse.move(px - i * 20, py + i * 4); await page.waitForTimeout(16) }
console.log('while dragging:', await page.evaluate(() => JSON.stringify({ held: __dbg.state().held, hero: __dbg.state().hero })))
await page.mouse.up()
await page.waitForTimeout(100)
console.log('after up:', await page.evaluate(() => JSON.stringify({ held: __dbg.state().held, hero: __dbg.state().hero })))
await browser.close()
